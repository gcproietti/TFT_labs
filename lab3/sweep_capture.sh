#!/bin/bash
#
# sweep_capture.sh - ATPG on a partial-scan netlist with 0, 2, 4, 10 capture cycles
#
# Usage (from ~/lab3):  ./sweep_capture.sh [name]        default name: b10_partial
#   reads run/<name>.v and run/<name>.spf, written by Design Compiler (Part D.2)
#
# For each value of set_atpg -capture_cycles the script WRITES a TestMAX command
# file in run/sweep_capture/<name>_cc<N>.tcl (the flow of atpg_b10_partial.tcl,
# plus the set_atpg line), runs it and collects one line.
#   0      basic-scan ATPG only (one capture cycle per pattern)
#   2..10  basic-scan ATPG, then fast-sequential ATPG with up to N capture cycles
# Result table: run/sweep_capture/<name>_table.txt

cd "$(dirname "${0}")"
root=${PWD}
name=${1:-b10_partial}
out=${root}/run/sweep_capture
mkdir -p "${out}"
for f in "run/${name}.v" "run/${name}.spf"; do
	[ -f "${f}" ] || { echo "${f} not found: run Design Compiler first (Part D.2)"; exit 1; }
done
top=$(grep -m1 -o "^ *module *[A-Za-z0-9_]*" "run/${name}.v" | awk '{print $2}')
table=${out}/${name}_table.txt

hdr="capture_cycles                     #faults      DT    PT    UD     AU     ND (NC/NO)   pats (basic/fast) test_cov fault_cov  cycles   time_s"
echo "${hdr}" > "${table}"

for n in 0 2 4 10; do
	tag=${name}_cc${n}
	cat > "${out}/${tag}.tcl" <<TCL
# generated by sweep_capture.sh - ${name}, capture cycles ${n}
set_messages -display
read_netlist ../../pdt2002.v -format verilog -insensitive -library
read_netlist ../${name}.v -format verilog -insensitive
run_build_model ${top}
set_drc ../${name}.spf
run_drc
report_nonscan_cells -summary
set_faults -model stuck
set_faults -summary verbose
set_faults -fault_coverage
add_faults -all
set_atpg -capture_cycles ${n}
run_atpg -auto_compression
report_summaries
write_faults ${tag}_faults.txt -all -replace -uncollapsed
write_patterns ${tag}.stil -format stil -replace
quit
TCL
	echo "running: ${name}, capture cycles ${n}"
	t0=$(date +%s)
	( cd "${out}" && tmax -shell "${tag}.tcl" < /dev/null > "${tag}.log" 2>&1 )
	t=$(( $(date +%s) - t0 ))
	echo "$("${root}/summary.sh" "${out}/${tag}.log" "${n}") ${t}" >> "${table}"
done

echo
cat "${table}"
echo
echo "Table written to run/sweep_capture/${name}_table.txt; logs and command files in run/sweep_capture/"
