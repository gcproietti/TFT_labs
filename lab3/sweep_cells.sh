#!/bin/bash
#
# sweep_cells.sh - basic-scan ATPG on b06 with cell constraints on the state register
# (15 settings: none, then 0, 1, X, OX, 0X, 1X, XX on state_reg[0] and on state_reg[2:0])
#
# Usage (from ~/lab3):  ./sweep_cells.sh
#
# For each setting the script WRITES a TestMAX command file in
# run/sweep_cells/<name>.tcl (the same flow as atpg_b06_cc.tcl), runs it and
# collects the fault summary. Result table: run/sweep_cells/table.txt
#
# Syntax: add_cell_constraints <value> <chain> -position {<first> [<last>]}
# Positions in chain "1" (0 = the cell next to scan-out, see report_scan_cells):
#   state_reg[0] = 4    state_reg[1] = 3    state_reg[2] = 2

cd "$(dirname "${0}")"
root=${PWD}
out=${root}/run/sweep_cells
mkdir -p "${out}"

# name | DRC commands (between set_drc and run_drc)
configs=(
	"01_none|"
	"02_state0=0|add_cell_constraints 0 1 -position 4"
	"03_state0=1|add_cell_constraints 1 1 -position 4"
	"04_state0=X|add_cell_constraints X 1 -position 4"
	"05_state0=OX|add_cell_constraints OX 1 -position 4"
	"06_state0=0X|add_cell_constraints 0X 1 -position 4"
	"07_state0=1X|add_cell_constraints 1X 1 -position 4"
	"08_state0=XX|add_cell_constraints XX 1 -position 4"
	"09_state0-2=0|add_cell_constraints 0 1 -position {2 4}"
	"10_state0-2=1|add_cell_constraints 1 1 -position {2 4}"
	"11_state0-2=X|add_cell_constraints X 1 -position {2 4}"
	"12_state0-2=OX|add_cell_constraints OX 1 -position {2 4}"
	"13_state0-2=0X|add_cell_constraints 0X 1 -position {2 4}"
	"14_state0-2=1X|add_cell_constraints 1X 1 -position {2 4}"
	"15_state0-2=XX|add_cell_constraints XX 1 -position {2 4}"
)

hdr="Setting                            #faults      DT    PT    UD     AU     ND (NC/NO)   pats (basic/fast) test_cov fault_cov  cycles"
echo "${hdr}" > "${out}/table.txt"

for c in "${configs[@]}"; do
	name=${c%%|*}
	cmds=${c#*|}
	tag=$(echo "${name}" | sed 's/=/_/g')
	tcl="${out}/${tag}.tcl"
	cat > "${tcl}" <<TCL
# generated by sweep_cells.sh - setting: ${name}
set_messages -display
read_netlist ../../pdt2002.v -format verilog -insensitive -library
read_netlist ../../b06_scan.v -format verilog -insensitive
run_build_model b06
set_drc ../../b06_scan.spf
${cmds}
run_drc
set_faults -model stuck
set_faults -summary verbose
set_faults -fault_coverage
add_faults -all
run_atpg -auto_compression
report_summaries
write_faults ${tag}_faults.txt -all -replace -uncollapsed
write_patterns ${tag}.stil -format stil -replace
quit
TCL
	echo "running: ${name}"
	( cd "${out}" && tmax -shell "${tcl}" < /dev/null > "${tag}.log" 2>&1 )
	"${root}/summary.sh" "${out}/${tag}.log" "${name}" >> "${out}/table.txt"
done

echo
cat "${out}/table.txt"
echo
echo "Table written to run/sweep_cells/table.txt; logs and command files in run/sweep_cells/"
