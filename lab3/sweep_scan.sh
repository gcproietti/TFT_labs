#!/bin/bash
#
# sweep_scan.sh - scan insertion with 1, 2, 4 chains on b10 and b12, then basic-scan ATPG
#
# Usage (from ~/lab3):  ./sweep_scan.sh            (b10 and b12)
#                       ./sweep_scan.sh b10        (only b10)
#
# For each circuit and number of chains the script WRITES
#   run/sweep_scan/<design>_<n>_dc.tcl    Design Compiler: the flow of b10_scan_insertion.tcl
#                                         with "-chain_count <n>"
#   run/sweep_scan/<design>_<n>_atpg.tcl  TestMAX: the flow of atpg_b10_scan.tcl
# runs them and collects one line per run. Result table: run/sweep_scan/table.txt
#
# Columns: chains, length of the longest chain (from the SPF), faults, test
# coverage, patterns, TAT computed with the formula of the lecture
#     TAT = (patterns + 1) x longest_chain + patterns          [clock cycles]
# and the number of test cycles reported by write_patterns.

cd "$(dirname "${0}")"
root=${PWD}
out=${root}/run/sweep_scan
mkdir -p "${out}"
designs=${*:-b10 b12}
dc=$(command -v dc_shell || command -v dc_shell-xg-t)
[ -z "${dc}" ] && echo "Design Compiler (dc_shell) not found in PATH" && exit 1

printf "%-8s %6s %8s %7s %8s %6s %10s %10s\n" design chains longest faults test_cov pats TAT_formula tool_cycles > "${out}/table.txt"

for d in ${designs}; do
	for n in 1 2 4; do
		tag=${d}_${n}
		# ------------------------------------------------ Design Compiler (runs in run/)
		cat > "${out}/${tag}_dc.tcl" <<TCL
# generated by sweep_scan.sh - ${d}, ${n} scan chain(s)
uplevel #0 source ../pdt2002.dc_setup.tcl
read_verilog ../${d}.v
current_design ${d}
link
check_design
report_area
set test_default_scan_style multiplexed_flip_flop
create_test_protocol -infer_asynch -infer_clock
dft_drc
set_scan_configuration -chain_count ${n}
preview_dft
insert_dft
dft_drc
report_scan_path -view existing -chain all
report_scan_path -view existing -cell all
report_area
write -hierarchy -format verilog -output sweep_scan/${tag}.v
write_test_protocol -output sweep_scan/${tag}.spf
quit
TCL
		echo "running Design Compiler: ${d}, ${n} chain(s)"
		( cd "${root}/run" && "${dc}" -f "${out}/${tag}_dc.tcl" < /dev/null > "${out}/${tag}_dc.log" 2>&1 )
		if [ ! -f "${out}/${tag}.spf" ]; then
			echo "  Design Compiler failed: see run/sweep_scan/${tag}_dc.log"
			printf "%-8s %6s %8s\n" "${d}" "${n}" "DC_FAILED" >> "${out}/table.txt"
			continue
		fi
		# ------------------------------------------------ TestMAX (runs in run/sweep_scan/)
		cat > "${out}/${tag}_atpg.tcl" <<TCL
# generated by sweep_scan.sh - ${d}, ${n} scan chain(s)
set_messages -display
read_netlist ../../pdt2002.v -format verilog -insensitive -library
read_netlist ${tag}.v -format verilog -insensitive
run_build_model ${d}
set_drc ${tag}.spf
run_drc
report_scan_chains
set_faults -model stuck
set_faults -summary verbose
set_faults -fault_coverage
add_faults -all
run_atpg -auto_compression
report_summaries
write_faults ${tag}_faults.txt -all -replace -uncollapsed
write_patterns ${tag}.stil -format stil -replace
quit
TCL
		echo "running TestMAX:         ${d}, ${n} chain(s)"
		( cd "${out}" && tmax -shell "${tag}_atpg.tcl" < /dev/null > "${tag}_atpg.log" 2>&1 )
		nch=$(grep -c "ScanChain " "${out}/${tag}.spf")
		L=$(grep -o "ScanLength *[0-9]*" "${out}/${tag}.spf" | awk '$2 > m {m = $2} END {print m + 0}')
		s=$("${root}/summary.sh" "${out}/${tag}_atpg.log" x)
		faults=$(echo "${s}" | awk '{print $2}')
		tc=$(echo "${s}" | awk '{print $11}')
		pats=$(echo "${s}" | awk '{print $9}')
		cyc=$(echo "${s}" | awk '{print $13}')
		tat=$(awk -v p="${pats}" -v l="${L}" 'BEGIN { if (p ~ /^[0-9]+$/) print (p + 1) * l + p; else print "-" }')
		printf "%-8s %6s %8s %7s %8s %6s %10s %10s\n" "${d}" "${nch}" "${L}" "${faults}" "${tc}" "${pats}" "${tat}" "${cyc}" >> "${out}/table.txt"
	done
done

echo
cat "${out}/table.txt"
echo
echo "Table written to run/sweep_scan/table.txt; logs, command files, netlists and SPFs in run/sweep_scan/"
