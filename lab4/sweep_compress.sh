#!/bin/bash
#
# sweep_compress.sh - b12: scan compression with several numbers of external and internal chains
#
# Usage (from ~/lab4):  ./sweep_compress.sh [stuck|transition]        default: stuck
#   CONFIGS="3:4 4:30" ./sweep_compress.sh        other configurations (external:internal)
#
# For each configuration the script WRITES
#   run/sweep_compress/b12_<e>x<i>_dc.tcl       Design Compiler: the flow of b12_compress.tcl with
#                                                set_scan_configuration -chain_count <e> and
#                                                set_scan_compression_configuration -chain_count <i>
#   run/sweep_compress/b12_<e>x<i>_comp.tcl     TestMAX, compressed mode (atpg_b12_comp.tcl)
#   run/sweep_compress/b12_<e>x<i>_bypass.tcl   TestMAX, compressor bypassed (atpg_b12_bypass.tcl)
# runs them and collects one line per configuration. Result table:
#   run/sweep_compress/table_<model>.txt
# Columns: external chains (scan-in pins), internal chains, longest chain in compressed mode and in
# bypass mode (from the SPFs), faults, and for each mode: patterns, test coverage, test cycles.

cd "$(dirname "${0}")"
root=${PWD}
model=${1:-stuck}
case ${model} in stuck|transition) ;; *) echo "Usage: $0 [stuck|transition]"; exit 1 ;; esac
configs=${CONFIGS:-"3:4 1:2 1:5 1:30 4:10 4:30"}
out=${root}/run/sweep_compress
mkdir -p "${out}"
dc=$(command -v dc_shell || command -v dc_shell-xg-t)
[ -z "${dc}" ] && echo "Design Compiler (dc_shell) not found in PATH" && exit 1
command -v tmax > /dev/null || { echo "TestMAX (tmax) not found in PATH"; exit 1; }
table=${out}/table_${model}.txt
printf "%4s %4s | %8s %8s | %7s | %6s %8s %8s | %6s %8s %8s\n" ext int L_comp L_bypass faults \
	c_pats c_cov c_cycles b_pats b_cov b_cycles > "${table}"

delay=""; atpg=""
if [ "${model}" == "transition" ]; then          # launch on capture, as atpg_b06_loc.tcl
	delay=$'add_pi_constraints 0 test_se\nset_delay -launch_cycle system_clock\nset_delay -nopi_changes'
	atpg="set_atpg -capture_cycles 2"
fi

for cfg in ${configs}; do
	e=${cfg%%:*}; i=${cfg##*:}
	tag=b12_${e}x${i}
	# ------------------------------------------------ Design Compiler (runs in run/)
	cat > "${out}/${tag}_dc.tcl" <<TCL
# generated by sweep_compress.sh - b12, ${e} external chain(s), ${i} internal chains
uplevel #0 source ../pdt2002.dc_setup.tcl
read_verilog ../b12.v
current_design b12
link
check_design
report_area
set_dft_configuration -scan_compression enable
set test_default_scan_style multiplexed_flip_flop
create_test_protocol -infer_asynch -infer_clock
dft_drc
set_scan_configuration -chain_count ${e}
set_scan_compression_configuration -chain_count ${i}
preview_dft
insert_dft
dft_drc
change_names -rules verilog -hierarchy
report_scan_path -view existing -chain all
report_scan_path -view existing -cell all
report_area
write -hierarchy -format verilog -output sweep_compress/${tag}.v
write_test_protocol -output sweep_compress/${tag}_scan.spf -test_mode Internal_scan
write_test_protocol -output sweep_compress/${tag}_scancompress.spf -test_mode ScanCompression_mode
quit
TCL
	echo "running Design Compiler: b12, ${e} external, ${i} internal chains"
	rm -f "${out}/${tag}.v" "${out}/${tag}_scan.spf" "${out}/${tag}_scancompress.spf"
	( cd "${root}/run" && "${dc}" -f "${out}/${tag}_dc.tcl" < /dev/null > "${out}/${tag}_dc.log" 2>&1 )
	if [ ! -f "${out}/${tag}_scancompress.spf" ]; then
		echo "  Design Compiler failed: see run/sweep_compress/${tag}_dc.log"
		printf "%4s %4s | %s\n" "${e}" "${i}" "DC_FAILED (see ${tag}_dc.log)" >> "${table}"
		continue
	fi
	# ------------------------------------------------ TestMAX, both modes (runs in run/sweep_compress/)
	for mode in comp bypass; do
		spf=${tag}_scancompress.spf; extra=$'report_compressors -load -verbose\nreport_compressors -unload -verbose'
		[ ${mode} == bypass ] && spf=${tag}_scan.spf && extra=""
		cat > "${out}/${tag}_${mode}_${model}.tcl" <<TCL
# generated by sweep_compress.sh - b12, ${e}x${i}, ${mode} mode, ${model} faults
set_messages -display
read_netlist ../../pdt2002.v -format verilog -insensitive -library
read_netlist ${tag}.v -format verilog -insensitive
run_build_model b12
set_drc ${spf}
${delay}
run_drc
report_scan_chains
${extra}
set_faults -model ${model}
set_faults -summary verbose
set_faults -fault_coverage
add_faults -all
${atpg}
run_atpg -auto_compression
report_summaries
write_faults ${tag}_${mode}_${model}_faults.txt -all -replace -uncollapsed
write_patterns ${tag}_${mode}_${model}.stil -format stil -replace
quit
TCL
		echo "running TestMAX:         b12, ${e}x${i}, ${mode} mode, ${model}"
		( cd "${out}" && tmax -shell "${tag}_${mode}_${model}.tcl" < /dev/null > "${tag}_${mode}_${model}.log" 2>&1 )
	done
	lc=$(grep -o "ScanLength *[0-9]*" "${out}/${tag}_scancompress.spf" | awk '$2 > m {m = $2} END {print m + 0}')
	lb=$(grep -o "ScanLength *[0-9]*" "${out}/${tag}_scan.spf" | awk '$2 > m {m = $2} END {print m + 0}')
	sc=$("${root}/summary.sh" "${out}/${tag}_comp_${model}.log" x)
	sb=$("${root}/summary.sh" "${out}/${tag}_bypass_${model}.log" x)
	f=$(echo "${sc}" | awk '{print $2}')
	cp=$(echo "${sc}" | awk '{print $9}');  cc=$(echo "${sc}" | awk '{print $11}'); cy=$(echo "${sc}" | awk '{print $13}')
	bp=$(echo "${sb}" | awk '{print $9}');  bc=$(echo "${sb}" | awk '{print $11}'); by=$(echo "${sb}" | awk '{print $13}')
	printf "%4s %4s | %8s %8s | %7s | %6s %8s %8s | %6s %8s %8s\n" "${e}" "${i}" "${lc}" "${lb}" "${f}" \
		"${cp}" "${cc}" "${cy}" "${bp}" "${bc}" "${by}" >> "${table}"
done

echo
cat "${table}"
echo
echo "Table written to run/sweep_compress/table_${model}.txt; logs, command files, netlists and SPFs in run/sweep_compress/"
