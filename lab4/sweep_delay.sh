#!/bin/bash
#
# sweep_delay.sh - b06: stuck-at ATPG and transition-delay ATPG with different launch settings
#
# Usage (from ~/lab4):  ./sweep_delay.sh
#
# For each setting the script WRITES a TestMAX command file in run/sweep_delay/<row>.tcl
# (the flow of atpg_b06_los.tcl / atpg_b06_loc.tcl), runs it and collects one line.
#   01_stuck          stuck-at faults, basic-scan ATPG (the reference of Lab 3)
#   02_los            transition, launch on shift (set_delay -launch_cycle last_shift)
#   03_loc_nopi       transition, launch on capture, PIs held, test_se constrained to 0
#   04_loc_pi         transition, launch on capture, PIs may change, test_se constrained to 0
#   05_loc_nopi_free  as 03, WITHOUT the constraint on test_se (the setting of the 2025 lab)
# Result table: run/sweep_delay/table.txt

cd "$(dirname "${0}")"
root=${PWD}
out=${root}/run/sweep_delay
mkdir -p "${out}"
command -v tmax > /dev/null || { echo "TestMAX (tmax) not found in PATH"; exit 1; }
table=${out}/table.txt
echo "setting                            #faults      DT    PT    UD     AU     ND (NC/NO)   pats (basic/fast) test_cov fault_cov  cycles" > "${table}"

for row in 01_stuck 02_los 03_loc_nopi 04_loc_pi 05_loc_nopi_free; do
	drc=""; model=transition; atpg=""
	case ${row} in
		01_stuck)         model=stuck ;;
		02_los)           drc="set_delay -launch_cycle last_shift" ;;
		03_loc_nopi)      drc=$'add_pi_constraints 0 test_se\nset_delay -launch_cycle system_clock\nset_delay -nopi_changes'
		                  atpg="set_atpg -capture_cycles 2" ;;
		04_loc_pi)        drc=$'add_pi_constraints 0 test_se\nset_delay -launch_cycle system_clock\nset_delay -pi_changes'
		                  atpg="set_atpg -capture_cycles 2" ;;
		05_loc_nopi_free) drc=$'set_delay -launch_cycle system_clock\nset_delay -nopi_changes'
		                  atpg="set_atpg -capture_cycles 2" ;;
	esac
	cat > "${out}/${row}.tcl" <<TCL
# generated by sweep_delay.sh - b06, ${row}
set_messages -display
read_netlist ../../pdt2002.v -format verilog -insensitive -library
read_netlist ../../b06_scan.v -format verilog -insensitive
run_build_model b06
set_drc ../../b06_scan.spf
${drc}
run_drc
set_faults -model ${model}
set_faults -summary verbose
set_faults -fault_coverage
add_faults -all
${atpg}
run_atpg -auto_compression
report_summaries
write_faults ${row}_faults.txt -all -replace -uncollapsed
write_patterns ${row}.stil -format stil -replace
quit
TCL
	echo "running: b06, ${row}"
	( cd "${out}" && tmax -shell "${row}.tcl" < /dev/null > "${row}.log" 2>&1 )
	"${root}/summary.sh" "${out}/${row}.log" "${row}" >> "${table}"
done

echo
cat "${table}"
echo
echo "Table written to run/sweep_delay/table.txt; command files, logs, fault lists and patterns in run/sweep_delay/"
