#!/bin/bash
#
# sweep_atpg.sh - combinational ATPG on c6288 with PI constraints and PO masks
#
# Usage (from ~/lab2):  ./sweep_atpg.sh
#
# For each configuration the script WRITES a TestMAX command file in
# run/sweep_atpg/<name>.tcl (the same flow as atpg_c6288.tcl, plus the
# constraint commands), runs it and collects the fault summary.
# Result table: run/sweep_atpg/table.txt

cd "$(dirname "${0}")"
root=${PWD}
out=${root}/run/sweep_atpg
mkdir -p "${out}"

ALL_POS=$(for i in $(seq 31 -1 0); do echo "datao(${i})"; done)
pi3() { for i in 0 1 2; do echo "add_pi_constraints ${1} datai(${i})"; done; }
po13() { for i in 1 2 3; do echo "add_po_masks datao(${i})"; done; }
all_but_1_3() { for p in ${ALL_POS}; do
	case ${p} in "datao(1)"|"datao(2)"|"datao(3)") ;; *) echo "add_po_masks ${p}" ;; esac
done; }

# name | DRC commands
configs=(
	"01_none|"
	"02_datai(0)=0|add_pi_constraints 0 datai(0)"
	"03_datai(0)=1|add_pi_constraints 1 datai(0)"
	"04_datai(1)=X|add_pi_constraints X datai(1)"
	"05_datai(0-2)=0|$(pi3 0)"
	"06_datai(0-2)=1|$(pi3 1)"
	"07_datai(0-2)=X|$(pi3 X)"
	"08_datai(0-2)=X+mask_datao(1-3)|$(pi3 X)
$(po13)"
	"09_datai(0-2)=X+mask_all_but_datao(1-3)|$(pi3 X)
$(all_but_1_3)"
	"10_mask_all|add_po_masks -all"
)

hdr="Configuration                              #faults      DT    PT    UD     AU     ND (NC/NO)   pats  test_cov fault_cov"
echo "${hdr}" > "${out}/table.txt"

for c in "${configs[@]}"; do
	name=${c%%|*}
	cmds=${c#*|}
	tag=$(echo "${name}" | sed 's/[()]//g; s/=/_/g; s/+/__/g')
	tcl="${out}/${tag}.tcl"
	cat > "${tcl}" <<TCL
# generated by sweep_atpg.sh - configuration: ${name}
set_messages -display
read_netlist ../../pdt2002.v -format verilog -insensitive -library
read_netlist ../../c6288.vhd -format vhdl -insensitive
run_build_model c6288
${cmds}
run_drc
set_faults -model stuck
set_faults -summary verbose
set_faults -fault_coverage
add_faults -all
run_atpg -auto_compression
report_summaries
write_faults ${tag}_faults.txt -all -replace -uncollapsed
quit
TCL
	echo "running: ${name}"
	( cd "${out}" && tmax -shell "${tcl}" < /dev/null > "${tag}.log" 2>&1 )
	"${root}/summary.sh" "${out}/${tag}.log" "${name}" >> "${out}/table.txt"
done

echo
cat "${out}/table.txt"
echo
echo "Table written to run/sweep_atpg/table.txt; logs and command files in run/sweep_atpg/"
