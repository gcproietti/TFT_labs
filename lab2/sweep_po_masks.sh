#!/bin/bash
#
# sweep_po_masks.sh - fault simulation of c6288.stil with different PO masks
#
# Usage (from ~/lab2):  ./sweep_po_masks.sh
#
# For each configuration the script WRITES a TestMAX command file in
# run/sweep_po/<name>.tcl, runs it and collects the fault summary with
# summary.sh. Read at least one of the generated .tcl files: it is the
# same flow as your fsim_c6288.tcl, plus the add_po_masks commands.
# Result table: run/sweep_po/table.txt

cd "$(dirname "${0}")"
root=${PWD}
out=${root}/run/sweep_po
mkdir -p "${out}"

# all output ports, in the order of the STIL file
ALL_POS=$(for i in $(seq 31 -1 0); do echo "datao(${i})"; done)

# masks for "every output except datao(1)..datao(3)": one add_po_masks per port
all_but_1_3() { for p in ${ALL_POS}; do
	case ${p} in "datao(1)"|"datao(2)"|"datao(3)") ;; *) echo "add_po_masks ${p}" ;; esac
done; }

# name | DRC commands
configs=(
	"none|"
	"datao(1)|add_po_masks datao(1)"
	"datao(2)|add_po_masks datao(2)"
	"datao(3)|add_po_masks datao(3)"
	"datao(1)-datao(3)|add_po_masks datao(1)
add_po_masks datao(2)
add_po_masks datao(3)"
	"all_but_datao(1)-datao(3)|$(all_but_1_3)"
	"all|add_po_masks -all"
)

hdr="PO masks                                   #faults      DT    PT    UD     AU     ND (NC/NO)   pats  test_cov fault_cov"
echo "${hdr}" > "${out}/table.txt"

for c in "${configs[@]}"; do
	name=${c%%|*}
	cmds=${c#*|}
	tag=$(echo "${name}" | sed 's/[()]//g')
	tcl="${out}/${tag}.tcl"
	cat > "${tcl}" <<TCL
# generated by sweep_po_masks.sh - PO masks: ${name}
set_messages -display
read_netlist ../../pdt2002.v -format verilog -insensitive -library
read_netlist ../../c6288.vhd -format vhdl -insensitive
run_build_model c6288
${cmds}
run_drc ../../c6288.stil
set_patterns -external ../../c6288.stil
run_simulation
set_faults -model stuck
set_faults -summary verbose
set_faults -fault_coverage
add_faults -all
run_fault_sim
report_summaries
write_faults ${tag}_faults.txt -all -replace -uncollapsed
quit
TCL
	echo "running: PO masks = ${name}"
	( cd "${out}" && tmax -shell "${tcl}" < /dev/null > "${tag}.log" 2>&1 )
	"${root}/summary.sh" "${out}/${tag}.log" "${name}" >> "${out}/table.txt"
done

echo
cat "${out}/table.txt"
echo
echo "Table written to run/sweep_po/table.txt; logs and command files in run/sweep_po/"
